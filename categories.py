from abc import ABC, abstractmethod
from typing import Dict, Optional


class CategoryStore(ABC):
    """Maps a merchant name (שם בית עסק) to a category (категория)."""

    @abstractmethod
    def categorize(self, merchant_name: Optional[str]) -> Optional[str]:
        """Return the category for a merchant name, or None if unknown."""

    @abstractmethod
    def contragent(self, merchant_name: Optional[str]) -> Optional[str]:
        """Return the contragent for a merchant name, or None if unknown."""


